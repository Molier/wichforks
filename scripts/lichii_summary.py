#!/usr/bin/env python3
"""Generate docs/LICHII-REPORTS.md from data/lichii-reports.json."""

from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "lichii-reports.json"
OUT = ROOT / "docs" / "LICHII-REPORTS.md"
STATUS_ORDER = ["Perfect", "Playable", "Runs", "Loads", "Unplayable"]
PROFANITY_RE = re.compile(r"\b(shit|fuck(?:ing)?|damn)\b", re.I)
GAME_SHORT = {
    "The Legend of Zelda: Ocarina of Time": "Zelda: OoT",
    "Mario Kart World": "Mario Kart World",
    "Donkey Kong Bananza": "Donkey Kong Bananza",
    "Pokémon Pokopia": "Pokémon Pokopia",
    "Pokemon Pokopia": "Pokémon Pokopia",
}


def short(value: str, limit: int = 42) -> str:
    value = re.sub(r"\s+", " ", value or "").strip()
    value = value.replace("|", "/").replace("\u2013", "-").replace("\u2014", "-")
    if not value:
        return "not stated"
    return value if len(value) <= limit else value[: limit - 3].rstrip() + "..."


def clean(value: str, limit: int = 150) -> str:
    value = re.sub(r"\s+", " ", value or "").strip()
    value = re.sub(r"\ba shit amount of time\b", "a very long time", value, flags=re.I)
    value = PROFANITY_RE.sub("[expletive]", value)
    value = value.replace("|", "/").replace("\u2013", "-").replace("\u2014", "-")
    if len(value) > limit:
        value = value[: limit - 3].rstrip() + "..."
    return value


def fps_label(row: dict) -> str:
    low, high = row.get("fps_min"), row.get("fps_max")
    if low is None or high is None:
        return ""
    return str(low) if low == high else f"{low}-{high}"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    reports = data["reports"]
    by_game = Counter(row["game"] for row in reports)
    by_status = Counter(row["status"] for row in reports)
    by_build = Counter(row.get("build_family") or "not stated" for row in reports)
    by_vendor = Counter(row.get("gpu_vendor") or "Unknown" for row in reports)
    by_os = Counter(row.get("os_family") or "Unknown" for row in reports)
    fps_rows = [row for row in reports if row.get("fps_min") is not None]

    lines = [
        "# Lichii public compatibility reports",
        "",
        "<!-- Generated by scripts/lichii_summary.py. Do not edit by hand. -->",
        "",
        f"Public reports from [lichii.zortos.me/reports]({data['source']}), scraped {data['scraped']}. "
        f"The dataset has {data['count']} reports and {len(data['errors'])} errors. Usernames are not collected.",
        "",
        "These are player-submitted compatibility reports, not benchmarks. Status labels are the site's own. "
        "A report marked Runs is not necessarily playable. The raw structured data is in "
        "[data/lichii-reports.json](../data/lichii-reports.json).",
        "",
        "## Coverage",
        "",
    ]
    lines += table(["Game", "Reports"], [[clean(GAME_SHORT.get(game, game), 200), str(count)] for game, count in by_game.most_common()])
    lines += ["", "## Status", ""]
    lines += table(
        ["Status", "Reports"],
        [[status, str(by_status.get(status, 0))] for status in STATUS_ORDER if by_status.get(status, 0)]
        + [[status, str(count)] for status, count in by_status.most_common() if status not in STATUS_ORDER],
    )
    lines += ["", "## Builds", ""]
    lines += table(["Build", "Reports"], [[build, str(count)] for build, count in by_build.most_common(12)])
    lines += ["", "## Hardware and OS", ""]
    lines += table(
        ["GPU vendor", "Reports"],
        [[vendor, str(count)] for vendor, count in by_vendor.most_common()],
    )
    lines += [""]
    lines += table(["OS", "Reports"], [[os_name, str(count)] for os_name, count in by_os.most_common()])

    nvidia = [row for row in reports if row.get("gpu_vendor") == "NVIDIA"]
    amd = [row for row in reports if row.get("gpu_vendor") == "AMD"]
    nvidia_good = sum(1 for row in nvidia if row["status"] in {"Perfect", "Playable"})
    amd_good = sum(1 for row in amd if row["status"] in {"Perfect", "Playable"})
    oot = [row for row in reports if "Ocarina" in row["game"]]
    oot_fps = [row for row in oot if row.get("fps_min") is not None]

    lines += [
        "",
        "## What stands out",
        "",
        f"- OoT is {len(oot)} of {len(reports)} reports. Build 93 is the most reported ({by_build.get('build-93', 0)}), "
        f"build 95 second ({by_build.get('build-95', 0)}) and build 88 third ({by_build.get('build-88', 0)}).",
        f"- Status mix: {by_status.get('Playable', 0)} Playable, {by_status.get('Runs', 0)} Runs, "
        f"{by_status.get('Unplayable', 0)} Unplayable, {by_status.get('Loads', 0)} Loads, {by_status.get('Perfect', 0)} Perfect.",
        f"- NVIDIA reports are {nvidia_good}/{len(nvidia)} Playable or Perfect. AMD is {amd_good}/{len(amd)}. "
        "Intel and Apple samples are too small to rank.",
        f"- Windows is {by_os.get('Windows', 0)} reports, Linux {by_os.get('Linux', 0)}, macOS {by_os.get('macOS', 0)}.",
        f"- {len(fps_rows)} reports mention an FPS number. OoT FPS mentions run from "
        f"{min(row['fps_min'] for row in oot_fps)} to {max(row['fps_max'] for row in oot_fps)} FPS. "
        "Scene, shader compilation and frame generation explain most of the spread.",
        "- Shader mentions are the most common technical theme (117 reports), followed by crashes (60) and stutter (58).",
        "",
        "## Reports with an FPS number",
        "",
        "The 35 most recent reports with a numeric FPS value. The full list is in the JSON dataset.",
        "",
    ]

    fps_rows.sort(key=lambda row: (row["date"], row["game"]), reverse=True)
    selected = fps_rows[:35]
    lines += table(
        ["Date", "Game", "Build", "Status", "CPU", "GPU", "RAM", "FPS", "Note"],
        [
            [
                f"[{row['date']}]({row['url']})",
                clean(GAME_SHORT.get(row["game"], row["game"]), 200),
                short(row.get("build_family") or row.get("build") or ""),
                row["status"],
                short(row.get("cpu", "")),
                short(row.get("gpu", "")),
                str(row.get("ram_gb") or "?"),
                fps_label(row),
                clean(row.get("what_happened") or row.get("title") or ""),
            ]
            for row in selected
        ],
    )

    lines += [
        "",
        "## Source and limits",
        "",
        "- Source: [Lichii public reports](https://lichii.zortos.me/reports). The scraper reads the sitemap and the public report pages only.",
        "- It does not call the authenticated or disallowed API endpoints, and it waits between requests.",
        "- The site labels are subjective and the reports are not controlled tests. One report is an anecdote.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(reports)} reports, {len(fps_rows)} with FPS)")


if __name__ == "__main__":
    main()
